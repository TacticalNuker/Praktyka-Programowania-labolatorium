# Exemplary calculator functions

"""Moduł kalkulatora"""

def add(a: int, b: int) -> int:
    """Dodawanie"""
    return a + b


def subtract(a: int, b: int) -> int:
    """Odejmowanie"""
    return a - b


def multiply(a: int, b: int) -> int:
    """Mnożenie"""
    return a * b


def divide(a: int, b: int) -> int:
    """Dzielenie"""
    return a / b
